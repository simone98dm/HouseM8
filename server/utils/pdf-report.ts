import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import type { Expense } from '../repositories/interfaces/IExpenseRepository';

export interface ReportData {
  houseName: string;
  year: number;
  month: number;
  expenses: Expense[];
  totalAmount: number;
  currency: string;
}

const MONTH_NAMES = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December',
];

export async function generateMonthlyReportPdf(
  data: ReportData,
): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const fontBold = await pdf.embedFont(StandardFonts.HelveticaBold);

  const page = pdf.addPage([595, 842]); // A4
  const { width, height } = page.getSize();
  const margin = 50;
  let y = height - margin;

  const drawText = (
    text: string,
    x: number,
    yPos: number,
    size: number,
    bold = false,
    color = rgb(0.1, 0.1, 0.1),
  ) => {
    page.drawText(text, {
      x,
      y: yPos,
      size,
      font: bold ? fontBold : font,
      color,
    });
  };

  // Header
  drawText('House-m8', margin, y, 20, true, rgb(0.27, 0.35, 0.9));
  y -= 30;

  const monthLabel = `${MONTH_NAMES[(data.month - 1) % 12]} ${data.year}`;
  drawText(`Monthly Expense Report — ${monthLabel}`, margin, y, 14, true);
  y -= 18;
  drawText(data.houseName, margin, y, 11, false, rgb(0.4, 0.4, 0.4));
  y -= 30;

  // Divider
  page.drawLine({
    start: { x: margin, y },
    end: { x: width - margin, y },
    thickness: 1,
    color: rgb(0.85, 0.85, 0.85),
  });
  y -= 20;

  // Table header
  const colDesc = margin;
  const colDate = width - margin - 140;
  const colAmt = width - margin - 50;

  drawText('Description', colDesc, y, 9, true, rgb(0.5, 0.5, 0.5));
  drawText('Date', colDate, y, 9, true, rgb(0.5, 0.5, 0.5));
  drawText('Amount', colAmt, y, 9, true, rgb(0.5, 0.5, 0.5));
  y -= 16;

  page.drawLine({
    start: { x: margin, y },
    end: { x: width - margin, y },
    thickness: 0.5,
    color: rgb(0.9, 0.9, 0.9),
  });
  y -= 14;

  // Rows
  for (const expense of data.expenses) {
    if (y < margin + 60) {
      // New page if needed
      const newPage = pdf.addPage([595, 842]);
      y = newPage.getSize().height - margin;
    }

    const desc =
      expense.description.length > 50
        ? expense.description.slice(0, 47) + '...'
        : expense.description;

    const dateStr = new Date(expense.created_at).toLocaleDateString('en-GB');
    const amtStr = `${data.currency} ${expense.total_amount.toFixed(2)}`;

    drawText(desc, colDesc, y, 9);
    drawText(dateStr, colDate, y, 9);
    drawText(amtStr, colAmt - (amtStr.length - 1) * 4, y, 9);
    y -= 16;
  }

  // Total
  y -= 10;
  page.drawLine({
    start: { x: margin, y },
    end: { x: width - margin, y },
    thickness: 1,
    color: rgb(0.27, 0.35, 0.9),
  });
  y -= 18;

  const totalStr = `${data.currency} ${data.totalAmount.toFixed(2)}`;
  drawText('Total', colDesc, y, 10, true);
  drawText(
    totalStr,
    colAmt - (totalStr.length - 1) * 4,
    y,
    10,
    true,
    rgb(0.27, 0.35, 0.9),
  );

  // Footer
  drawText(
    `Generated by House-m8 on ${new Date().toLocaleDateString('en-GB')}`,
    margin,
    margin,
    8,
    false,
    rgb(0.6, 0.6, 0.6),
  );

  return pdf.save();
}
